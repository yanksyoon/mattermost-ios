//
// Why the bundled table and not only the 60 names T34 shipped:
//  - T34's `EmojiShortcodes.table` exists to *draw* a `:name:` that is already in a post. A picker
//    built from it would offer 60 of the ~1,800 shortcodes the server itself resolves, so the
//    acceptance sentence "the picker lists system emoji" would be false in the only way that
//    matters — a reader looking for `:shipit:`-adjacent emoji finding nothing.
//  - the canonical-alias rule (`getEmojiFirstAlias`) needs the whole alias table, not a sample:
//    `thumbsup` and `+1` are the same reaction, and the client has to know that to draw one pill.
//
// The data is a value type loaded once from the app bundle; nothing here is main-actor isolated, so
// the pure list derivations (`PostListDerivation`) can canonicalise names without hopping actors.

import Foundation

/// One system emoji, as the bundled table stores it.
struct SystemEmoji: Codable, Equatable, Identifiable, Sendable {
    /// The canonical shortcode — upstream's `short_names[0]`. This is what gets *sent* when the
    /// reader picks the emoji (`getEmojiFirstAlias`), so `:thumbsup:` is sent as `+1`.
    var name: String
    /// Every shortcode the server resolves for this emoji, canonical first.
    var aliases: [String]
    /// The grapheme the picker draws (`🎉`). Derived from the datasource's code-point sequence, so
    /// no image assets are needed for the system set.
    var char: String
    /// The datasource category key (`smileys-emotion`, …) — the picker's section id.
    var category: String

    var id: String { name }
}

/// One picker section of the system set.
struct SystemEmojiCategory: Identifiable, Equatable, Sendable {
    let id: String
    let title: String
    let emojis: [SystemEmoji]
}

/// The bundled resource's shape (`Mattermost/Resources/emoji.json`).
struct SystemEmojiPayload: Decodable, Equatable, Sendable {
    var source: String
    var license: String
    var categoryOrder: [String]
    var categoryTitles: [String: String]
    var emojis: [SystemEmoji]

    enum CodingKeys: String, CodingKey {
        case source, license, emojis
        case categoryOrder = "category_order"
        case categoryTitles = "category_titles"
    }
}

/// The system emoji set: lookup by any alias, canonical alias, sections, and the picker's ranking.
///
/// Immutable and cheap to share. `SystemEmojiCatalogue.shared` is the app's one instance; tests build
/// their own from a few entries so the rules (not the data) are what they pin.
struct SystemEmojiCatalogue: Equatable, Sendable {

    static let resourceName = "emoji"

    let emojis: [SystemEmoji]
    let categories: [SystemEmojiCategory]
    private let byAlias: [String: Int]
    private let canonicalByAlias: [String: String]

    /// The app-wide table. Loaded from the bundle; if the resource is missing (a target that forgot
    /// to copy it) the catalogue degrades to T34's 60-name table rather than to an empty picker, and
    /// says so in `degradedReason` — a silent empty picker is the failure mode that would waste an
    /// hour of a live run.
    static let shared: SystemEmojiCatalogue = {
        if let loaded = SystemEmojiCatalogue(bundle: .main) { return loaded }
        return SystemEmojiCatalogue(fallback: EmojiShortcodes.table)
    }()

    /// Non-nil when `shared` could not read the bundled resource.
    var degradedReason: String?

    init(emojis: [SystemEmoji],
         categoryOrder: [String],
         categoryTitles: [String: String],
         degradedReason: String? = nil) {
        self.emojis = emojis
        self.degradedReason = degradedReason

        var indexByAlias: [String: Int] = [:]
        var canonical: [String: String] = [:]
        for (offset, emoji) in emojis.enumerated() {
            // The canonical name is an alias too, so it is inserted by the same loop.
            for alias in emoji.aliases where !alias.isEmpty {
                let key = alias.lowercased()
                if indexByAlias[key] == nil { indexByAlias[key] = offset }
                if canonical[key] == nil { canonical[key] = emoji.name }
            }
            if emoji.aliases.isEmpty {
                indexByAlias[emoji.name.lowercased()] = offset
                canonical[emoji.name.lowercased()] = emoji.name
            }
        }
        self.byAlias = indexByAlias
        self.canonicalByAlias = canonical

        // Sections follow upstream's `CategoryNames` order for the categories the resource carries;
        // a category the payload does not mention keeps its position at the end instead of vanishing.
        var remaining = Dictionary(grouping: emojis, by: \.category)
        var sections: [SystemEmojiCategory] = []
        for key in categoryOrder {
            guard let members = remaining.removeValue(forKey: key), !members.isEmpty else { continue }
            sections.append(SystemEmojiCategory(id: key,
                                                title: categoryTitles[key] ?? key,
                                                emojis: members))
        }
        for key in remaining.keys.sorted() {
            guard let members = remaining[key] else { continue }
            sections.append(SystemEmojiCategory(id: key,
                                                title: categoryTitles[key] ?? key,
                                                emojis: members))
        }
        self.categories = sections
    }

    /// Read the bundled resource. Returns nil when it is missing or malformed — the caller decides
    /// how to degrade (see `shared`).
    init?(bundle: Bundle) {
        guard let url = bundle.url(forResource: Self.resourceName, withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let payload = try? JSONDecoder().decode(SystemEmojiPayload.self, from: data) else {
            return nil
        }
        self.init(emojis: payload.emojis,
                  categoryOrder: payload.categoryOrder,
                  categoryTitles: payload.categoryTitles)
    }

    /// T34's hand-written table, used only when the bundled resource is absent.
    init(fallback table: [String: String]) {
        var entries: [SystemEmoji] = []
        var seen = Set<String>()
        for (name, character) in table.sorted(by: { $0.key < $1.key }) where seen.insert(name).inserted {
            entries.append(SystemEmoji(name: name, aliases: [name], char: character,
                                       category: "symbols"))
        }
        self.init(emojis: entries,
                  categoryOrder: ["symbols"],
                  categoryTitles: ["symbols": "Symbols"],
                  degradedReason: "bundled emoji.json missing; using the \(entries.count)-name fallback")
    }

    // MARK: - Lookup

    func emoji(named name: String) -> SystemEmoji? {
        guard let index = byAlias[name.lowercased()] else { return nil }
        return emojis[index]
    }

    /// The shortcode to *send* for `name`: upstream's `getEmojiFirstAlias`. `nil` for a name the
    /// system table does not know (a server custom emoji, which keeps its own spelling).
    func canonicalName(for name: String) -> String? {
        canonicalByAlias[name.lowercased()]
    }

    /// The grapheme for a name, via any alias (`thumbsup` → 👍).
    func character(for name: String) -> String? {
        emoji(named: name)?.char
    }

    /// Whether this shortcode is one the system set resolves. A custom emoji whose name collides with
    /// a system one is drawn as the system glyph — the server resolves it the same way.
    func contains(_ name: String) -> Bool {
        byAlias[name.lowercased()] != nil
    }

    /// The whole category of an emoji, for "more like this" style suggestions.
    func category(of name: String) -> SystemEmojiCategory? {
        guard let emoji = emoji(named: name) else { return nil }
        return categories.first { $0.id == emoji.category }
    }

    // MARK: - Search

    /// Names matching `term`, best first. The ranking is upstream's `compareEmojis` rule:
    ///
    ///  * a name that *starts with* the term sorts before one that merely *contains* it;
    ///  * inside each tier, alphabetical — except that `thumbsup`/`+1` sort before everything and
    ///    `thumbsdown`/`-1` after it, the one hard-coded exception in upstream (`customComparisonRules`);
    ///  * a fuzzy tier (characters in order, e.g. `smle` → `smile`) comes last. Upstream uses Fuse and
    ///    a score cut-off; this is a deterministic subsequence tier instead, so the same query cannot
    ///    rank differently between two runs (documented as a limit in docs/t37-build-note.md).
    func search(_ term: String, limit: Int = 60) -> [SystemEmoji] {
        let needle = term.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !needle.isEmpty else { return [] }
        var best: [(rank: Int, name: String, emoji: SystemEmoji)] = []
        for emoji in emojis {
            // A name matches if it matches through *any* alias; the displayed name is the canonical.
            var rank = Int.max
            for alias in ([emoji.name] + emoji.aliases) {
                rank = min(rank, Self.rank(alias.lowercased(), needle))
            }
            guard rank < Int.max else { continue }
            best.append((rank, emoji.name, emoji))
        }
        return best
            .sorted { lhs, rhs in
                if lhs.rank != rhs.rank { return lhs.rank < rhs.rank }
                if lhs.name == rhs.name { return false }
                if let special = SystemEmojiCatalogue.compareSpecial(lhs.name, rhs.name) {
                    return special
                }
                return lhs.name < rhs.name
            }
            .prefix(limit)
            .map(\.emoji)
    }

    /// 0 = starts with, 1 = contains, 2 = subsequence, `Int.max` = no match.
    static func rank(_ name: String, _ needle: String) -> Int {
        if name.hasPrefix(needle) { return 0 }
        if name.contains(needle) { return 1 }
        var cursor = name.startIndex
        for character in needle {
            guard let found = name[cursor...].firstIndex(of: character) else { return Int.max }
            cursor = name.index(after: found)
        }
        return 2
    }

    /// Upstream's `customComparisonRules`: the two emoji whose names are shared with a *sentiment*
    /// (`thumbsup`/`+1`, `thumbsdown`/`-1`) are pinned to the ends of an alphabetical list.
    /// Returns nil when the pair is not special.
    static func compareSpecial(_ lhs: String, _ rhs: String) -> Bool? {
        func rule(_ name: String) -> Int {
            let head = name.split(separator: "_").first.map(String.init) ?? name
            switch head {
            case "thumbsup", "+1": return -1
            case "thumbsdown", "-1": return 1
            default: return 0
            }
        }
        let a = rule(lhs)
        let b = rule(rhs)
        guard a != b, a != 0 || b != 0 else { return nil }
        return a < b
    }
}
