// T44c — the signalling codec and the event decoder, pinned by fixtures.
//
// Two halves, both verifiable with no server:
//
//  1. **Framing.** The plugin type-asserts `data.data` to `[]byte` on the `sdp` action, and the core
//     server can only produce a `[]byte` from a MessagePack frame — a JSON text frame arrives as a
//     `string` and the plugin drops it ("invalid or missing sdp data"). So the assertable facts are
//     that our frame is a 3-entry MessagePack map (`seq`, `action`, `data.data` = bin) and that the
//     bin is an RFC 1950 zlib stream that a *Go/Python* zlib reader accepts. The zlib test fixture
//     below is produced by CPython's `zlib.compress`, which is the same stream format
//     `zlib.NewReader` (what the plugin uses) reads.
//
//  2. **Decoding.** Every `wsEvent*` the plugin can publish, decoded from a literal frame into a
//     typed `CallsEvent` — including the measured shapes that are easy to get wrong: `signal.data`
//     is a JSON **string** inside the event's `data`, `call_state.call` is too, and the `connID`
//     that says which session a signal belongs to lives on the event, not in the inner JSON.

import Foundation
import XCTest
@testable import Mattermost

final class T44CCallsCodecTests: XCTestCase {

    /// A realistic audio-only offer body. The CRLFs matter: an SDP is line-oriented and JSON-escapes
    /// them, which is exactly where a hand-rolled encoder broke during the spike.
    static let sdp = "v=0\r\n"
        + "o=- 4611731400430051336 2 IN IP4 127.0.0.1\r\n"
        + "s=-\r\n"
        + "t=0 0\r\n"
        + "a=group:BUNDLE 0\r\n"
        + "m=audio 9 UDP/TLS/RTP/SAVPF 111\r\n"
        + "c=IN IP4 0.0.0.0\r\n"
        + "a=mid:0\r\n"
        + "a=sendrecv\r\n"
        + "a=rtpmap:111 opus/48000/2\r\n"

    /// `zlib.compress(json.dumps({"type": "offer", "sdp": <the SDP above>}))` at CPython level 6.
    /// Generated by `scripts/t44c-fixtures.py`; regenerating it must produce this exact string or the
    /// interop claim below is void.
    static let pythonZlibOffer = "eJwtjEsLgzAQhP/KknNtNppqK+TQYguCiFTtyYv4KB40IT6glP73+mIOO7O7833J8FEVcYms60qTA+lLNadJYKazTgoDuM2YYzGOyC3EE7MsG0zwQ/AjDsx0jjiLLd+9MJYxCIS1nYu3lqNyb2noBfdt14p8LBsJF0i9iCZBTJ9JROPrK3oAYyumEDscV/SOapvS3W1fdaWuimlLelBtrty5DFKNPeVnRKTmciS/P/LgQj0="

    // MARK: - zlib

    /// The direction that decides compatibility: **we read a stream a Go/Python writer produced.**
    func testInflateReadsAPythonZlibStream() throws {
        let compressed = try XCTUnwrap(Data(base64Encoded: Self.pythonZlibOffer))
        XCTAssertTrue(CallsSDPCodec.hasZlibWrapper(compressed), "fixture must carry the RFC 1950 header")

        let description = try CallsSDPCodec.unpack(compressed)
        XCTAssertEqual(description.kind, .offer)
        XCTAssertEqual(description.sdp, Self.sdp)
    }

    /// The other direction: what we emit round-trips, and carries a valid RFC 1950 header
    /// (`0x78` CMF and a FLG that makes `(CMF << 8 | FLG) % 31 == 0`).
    func testDeflateEmitsAnRFC1950Stream() throws {
        let description = CallsSessionDescription(kind: .offer, sdp: Self.sdp)
        let packed = try CallsSDPCodec.pack(description)

        XCTAssertEqual(packed[0], 0x78, "CMF: deflate, 32K window")
        let cmf = Int(packed[0]) << 8 | Int(packed[1])
        XCTAssertEqual(cmf % 31, 0, "FLG must make the header a multiple of 31")

        // Compressing 223 bytes of SDP JSON must not grow it past a couple of zlib blocks.
        XCTAssertLessThan(packed.count, 300)

        let roundTripped = try CallsSDPCodec.unpack(packed)
        XCTAssertEqual(roundTripped, description)
    }

    func testInflateRejectsGarbage() {
        XCTAssertThrowsError(try CallsSDPCodec.unpack(Data([0x00, 0x01, 0x02, 0x03])))
    }

    /// A peer that sends raw DEFLATE (no zlib wrapper) is not what the plugin does — the codec must
    /// say so rather than silently produce truncated JSON.
    func testHasZlibWrapperDistinguishesRawDeflate() throws {
        let packed = try CallsSDPCodec.pack(CallsSessionDescription(kind: .offer, sdp: Self.sdp))
        XCTAssertTrue(CallsSDPCodec.hasZlibWrapper(packed))
        XCTAssertFalse(CallsSDPCodec.hasZlibWrapper(packed.dropFirst(2).dropLast(4)))
    }

    // MARK: - The MessagePack frame

    func testSDPFrameIsAMessagePackMapWithSeqActionAndBinaryPayload() throws {
        let description = CallsSessionDescription(kind: .answer, sdp: Self.sdp)
        let frame = try CallsSDPCodec.sdpFrame(seq: 7, description: description)

        var reader = MiniMessagePackReader(bytes: [UInt8](frame))
        guard case .map(let entries) = try reader.readValue() else {
            return XCTFail("the sdp frame must be a MessagePack map")
        }
        XCTAssertEqual(entries.count, 3, "seq + action + data, nothing else")
        XCTAssertNil(reader.remaining, "no trailing bytes after the map")

        XCTAssertEqual(entries["seq"], .int(7))
        XCTAssertEqual(entries["action"], .string("custom_com.mattermost.calls_sdp"))

        guard case .map(let data)? = entries["data"] else {
            return XCTFail("`data` must be a map holding the bin")
        }
        XCTAssertEqual(data.keys.sorted(), ["data"])
        guard case .binary(let payload)? = data["data"] else {
            return XCTFail("`data.data` must be a MessagePack **bin**, not a str: the plugin "
                           + "type-asserts []byte and drops a string")
        }

        // …and that bin is the zlib stream the plugin inflates.
        let unpacked = try CallsSDPCodec.unpack(payload)
        XCTAssertEqual(unpacked, description)
    }

    /// The seq is the client's next request sequence: the plugin ignores it, but the core socket uses
    /// it to correlate replies, so it must be an integer, not a string.
    func testSDPFrameSeqIsAnInteger() throws {
        let frame = try CallsSDPCodec.sdpFrame(seq: 128,
                                               description: .init(kind: .offer, sdp: Self.sdp))
        var reader = MiniMessagePackReader(bytes: [UInt8](frame))
        guard case .map(let entries) = try reader.readValue() else {
            return XCTFail("not a map")
        }
        XCTAssertEqual(entries["seq"], .int(128), "0xcc/0xcd encodings must still read back as int")
    }

    /// The inner JSON is `{"type": ..., "sdp": ...}` — the shape `server/websocket.go` unmarshals.
    func testDescriptionJSONUsesTypeAndSDPKeys() throws {
        let description = CallsSessionDescription(kind: .offer, sdp: Self.sdp)
        let object = try JSONSerialization.jsonObject(with: description.jsonBody) as? [String: Any]
        XCTAssertEqual(object?["type"] as? String, "offer")
        XCTAssertEqual(object?["sdp"] as? String, Self.sdp)
        XCTAssertEqual(Set(object?.keys.map { $0 } ?? []), ["type", "sdp"])
    }

    func testDescriptionRejectsAMissingSDPOrUnknownType() {
        XCTAssertThrowsError(try CallsSessionDescription(json: #"{"type":"offer"}"#))
        XCTAssertThrowsError(try CallsSessionDescription(json: #"{"type":"nonsense","sdp":"v=0"}"#))
        XCTAssertThrowsError(try CallsSessionDescription(json: "not json"))
    }

    /// `rollback` is a legal SDP type in the wire protocol but is not a Calls description; it decodes
    /// to a signal whose payload is `unknown`, never to a description.
    func testRollbackIsCarriedAsAnUnknownSignal() throws {
        let event = CallsEvent(name: "custom_com.mattermost.calls_signal",
                               data: callsRaw(#"{"connID":"abc","data":"{\"type\":\"rollback\"}"}"#))
        guard case .signal(let signal)? = event else { return XCTFail("expected a signal") }
        XCTAssertEqual(signal.payload, .unknown("rollback"))
        XCTAssertEqual(signal.connID, "abc")
    }
}

// MARK: - A tiny MessagePack reader (test-only)

/// Reads back exactly the subset `CallsMessagePack.encode` writes, so a test can assert the frame's
/// **structure** instead of comparing opaque bytes (zlib output is not byte-stable across builds).
struct MiniMessagePackReader {
    enum Value: Equatable {
        case int(Int)
        case string(String)
        case binary(Data)
        case map([String: Value])
        case array([Value])
        case bool(Bool)
        case null
    }

    let bytes: [UInt8]
    var index = 0

    init(bytes: [UInt8]) { self.bytes = bytes }

    var remaining: Int? { index == bytes.count ? nil : bytes.count - index }

    mutating func readValue() throws -> Value {
        let tag = try byte()
        switch tag {
        case 0x00...0x7f: return .int(Int(tag))
        case 0x80...0x8f: return try map(count: Int(tag & 0x0f))
        case 0x90...0x9f: return try array(count: Int(tag & 0x0f))
        case 0xa0...0xbf: return .string(try string(length: Int(tag & 0x1f)))
        case 0xc0: return .null
        case 0xc2: return .bool(false)
        case 0xc3: return .bool(true)
        case 0xc4: return .binary(try data(length: Int(try byte())))
        case 0xc5: return .binary(try data(length: Int(try bigEndian(2))))
        case 0xc6: return .binary(try data(length: Int(try bigEndian(4))))
        case 0xcc: return .int(Int(try byte()))
        case 0xcd: return .int(Int(try bigEndian(2)))
        case 0xce: return .int(Int(try bigEndian(4)))
        case 0xd9: return .string(try string(length: Int(try byte())))
        case 0xda: return .string(try string(length: Int(try bigEndian(2))))
        case 0xdc: return try array(count: Int(try bigEndian(2)))
        case 0xde: return try map(count: Int(try bigEndian(2)))
        default:
            throw NSError(domain: "MiniMessagePackReader", code: Int(tag),
                          userInfo: [NSLocalizedDescriptionKey: "unexpected tag \(tag)"])
        }
    }

    private mutating func map(count: Int) throws -> Value {
        var entries: [String: Value] = [:]
        for _ in 0..<count {
            guard case .string(let key) = try readValue() else {
                throw NSError(domain: "MiniMessagePackReader", code: 1)
            }
            entries[key] = try readValue()
        }
        return .map(entries)
    }

    private mutating func array(count: Int) throws -> Value {
        var values: [Value] = []
        for _ in 0..<count { values.append(try readValue()) }
        return .array(values)
    }

    private mutating func byte() throws -> UInt8 {
        guard index < bytes.count else {
            throw NSError(domain: "MiniMessagePackReader", code: 2,
                          userInfo: [NSLocalizedDescriptionKey: "ran out of bytes"])
        }
        defer { index += 1 }
        return bytes[index]
    }

    private mutating func data(length: Int) throws -> Data {
        guard index + length <= bytes.count else {
            throw NSError(domain: "MiniMessagePackReader", code: 3)
        }
        defer { index += length }
        return Data(bytes[index..<(index + length)])
    }

    private mutating func string(length: Int) throws -> String {
        String(decoding: try data(length: length), as: UTF8.self)
    }

    private mutating func bigEndian(_ width: Int) throws -> UInt64 {
        var value: UInt64 = 0
        for _ in 0..<width { value = value << 8 | UInt64(try byte()) }
        return value
    }
}

// MARK: - Shared fixture helpers

/// Build the `MMRawJSON` payload a socket frame would carry, from JSON text.
func callsRaw(_ json: String) -> MMRawJSON {
    let value = (try? JSONDecoder().decode(JSONValue.self, from: Data(json.utf8)))
        ?? .object([:])
    return MMRawJSON(value)
}
