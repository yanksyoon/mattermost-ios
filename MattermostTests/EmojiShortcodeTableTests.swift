// t_580df874 — reactions and post bodies resolve shortcodes through the full upstream table.
//
// The report: on a native channel view `👍 4` drew while `:lol-sob: 3` and `:camera_with_flash: 1`
// were literal text in the reaction pills. The pill's fallback was `EmojiShortcodes`, a hand-written
// 60-name sample; `camera_with_flash` is a *system* emoji the server resolves, so the pill should
// have drawn 📸. The sample is gone as the resolution path: `EmojiShortcodes.character(for:)` now
// reads `SystemEmojiCatalogue.shared`, the 1,805-emoji / 2,327-alias resource the picker already
// uses, generated by `scripts/t37_emoji_build.py` from upstream's Apache-2.0 `emoji.json`.
//
// Behaviour reference: mattermost/mattermost-mobile @ v2.45.0, `app/utils/emoji/index.ts`
// (`EmojiIndicesByAlias`) and `app/components/markdown/markdown.tsx` (a known shortcode → glyph, an
// unknown one → the literal text). Licence: Apache-2.0, docs/THIRD_PARTY_NOTICES.md §14.
//
// What is pinned here, in the order the card's acceptance asks for it:
//   1. the bundled table is present and complete (a missing resource must fail, not silently degrade);
//   2. names outside the old 60-name table draw their glyph, through any alias;
//   3. the same table answers the markdown renderer;
//   4. a custom emoji's image still wins, and `:name:` is only the text for a name neither knows.

import UIKit
import XCTest
@testable import Mattermost

final class EmojiShortcodeTableTests: XCTestCase {

    // MARK: - 1. The bundled table

    func testTheBundledTableIsCompleteAndNotDegraded() {
        let catalogue = SystemEmojiCatalogue.shared
        XCTAssertNil(catalogue.degradedReason,
                     "emoji.json must be in the app bundle, not the 60-name fallback: "
                     + (catalogue.degradedReason ?? ""))
        // Upstream's file at the pinned commit: 1,805 base emoji. A count well below that means the
        // resource regressed to a sample again, which is the defect this card is about.
        XCTAssertGreaterThan(catalogue.emojis.count, 1_700)
        let aliases = catalogue.emojis.reduce(0) { $0 + $1.aliases.count }
        XCTAssertGreaterThan(aliases, 2_200)
    }

    // MARK: - 2. Names outside the old hand-written table

    func testNamesOutsideTheOldHandTableDrawTheirGlyph() {
        // The three the card names, plus the one from the capture.
        XCTAssertEqual(EmojiShortcodes.character(for: "dolphin"), "🐬")
        XCTAssertEqual(EmojiShortcodes.character(for: "sparkling_heart"), "💖")
        XCTAssertEqual(EmojiShortcodes.character(for: "face_with_raised_eyebrow"), "🤨")
        XCTAssertEqual(EmojiShortcodes.character(for: "camera_with_flash"), "📸")
        // The lookup is case-insensitive, like the server's.
        XCTAssertEqual(EmojiShortcodes.character(for: "Dolphin"), "🐬")
    }

    func testEveryAliasInTheTableResolvesThroughTheOneEntryPoint() {
        // One source, not a parallel list: every alias the picker offers renders in a pill or a body.
        for emoji in SystemEmojiCatalogue.shared.emojis {
            for alias in emoji.aliases where !alias.isEmpty {
                XCTAssertEqual(EmojiShortcodes.character(for: alias), emoji.char,
                               "\(alias) must resolve to the same glyph the picker draws")
            }
        }
    }

    // MARK: - 3. The markdown renderer

    func testTheMarkdownRendererDrawsTheSameGlyphForANonTableName() {
        // `accessibilityText` walks the same `segments` the drawn paragraph does, so this is the
        // renderer's own resolution rather than a second lookup that could drift.
        XCTAssertEqual(MarkdownText.accessibilityText([.emoji(name: "dolphin")], custom: []), "🐬")
        XCTAssertEqual(MarkdownText.accessibilityText([.emoji(name: "camera_with_flash")], custom: []),
                       "📸")
    }

    // MARK: - 4. Precedence: custom image, then glyph, then literal text

    func testACustomEmojiImageWinsEvenWhenTheNameIsAlsoASystemOne() {
        // The server resolves its own emoji first; a team that uploaded `dolphin` expects its image.
        switch EmojiGlyph.resolve(image: image(), name: "dolphin") {
        case .image:
            break
        case .character(let glyph):
            XCTFail("a loaded custom emoji must draw its image, not \(glyph)")
        case .literal(let text):
            XCTFail("a loaded custom emoji must draw its image, not \(text)")
        }
    }

    func testAnImageThatHasNotLoadedYetFallsBackToTheSystemGlyph() {
        // `EmojiCatalogue.image(for:)` answers after the first draw; the pill must not stay literal
        // in the meantime (T34 review F7 measured exactly that with `:t34parrot:`).
        switch EmojiGlyph.resolve(image: nil, name: "dolphin") {
        case .character(let glyph):
            XCTAssertEqual(glyph, "🐬")
        case .image:
            XCTFail("no image was supplied")
        case .literal(let text):
            XCTFail("a system emoji must draw its glyph, not \(text)")
        }
    }

    func testANameNeitherTheServerNorTheTableKnowsStaysLiteral() {
        for name in ["t34parrot", "lol-sob", "not_a_real_emoji"] {
            switch EmojiGlyph.resolve(image: nil, name: name) {
            case .literal(let text):
                XCTAssertEqual(text, ":\(name):")
            case .character(let glyph):
                XCTFail("\(name) is not a system emoji; drew \(glyph)")
            case .image:
                XCTFail("no image was supplied for \(name)")
            }
        }
    }

    // MARK: - Fixtures

    private func image() -> UIImage {
        let format = UIGraphicsImageRendererFormat.default()
        format.opaque = false
        return UIGraphicsImageRenderer(size: CGSize(width: 2, height: 2), format: format).image { context in
            UIColor.systemTeal.setFill()
            context.fill(CGRect(x: 0, y: 0, width: 2, height: 2))
        }
    }
}
